/* =========================================================
   書き込みの直列化

   storeはDB全体を1行のJSONで持っているため、更新は必ず
   「読む → 変える → 書く」の3手順になる。この途中で別の処理が
   割り込むと、両方が同じ内容を読んでしまい、後に書いたほうが
   先の変更を消してしまう（＝保存したはずの内容が失われる）。

   ここを通した処理は1つずつ順番に実行されるので、その事故が起きない。

   なお本番のTurso（ネットワーク越し）では読み書きのたびに待ちが発生するため
   割り込みが起きるが、ローカルの開発用SQLiteでは待ちが発生せず割り込みが
   起きない。「ローカルで再現しないから問題ない」とは言えないので注意。
   ========================================================= */

/* 直前の処理が終わってから次を始める、という鎖をつないでいく */
let chain = Promise.resolve();

function withDBLock(fn) {
  // 前の処理が失敗しても次は動かす（巻き添えで止めない）ため、成否どちらでも続ける
  const run = chain.then(fn, fn);
  chain = run.then(() => undefined, () => undefined);
  return run;
}

/* テスト用。鎖を初期状態に戻す */
function _resetForTest() {
  chain = Promise.resolve();
}

module.exports = { withDBLock, _resetForTest };
