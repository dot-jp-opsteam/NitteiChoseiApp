import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const requests=[],messages=[];
const context=vm.createContext({console,currentTab:'',document:{},closeSheet:()=>{},toast:message=>messages.push(message),api:(path,options)=>new Promise(resolve=>requests.push({body:JSON.parse(options.body),resolve}))});
vm.runInContext(readFileSync(new URL('../availability-ui.js',import.meta.url),'utf8'),context);
vm.runInContext(`AVGOOGLE={key:'staff|week',events:[{id:'one',calendar_id:'primary',start:'2030-01-01T10:00:00Z',end:'2030-01-01T12:00:00Z',blocking_start:'2030-01-01T10:00:00Z',blocking_end:'2030-01-01T12:00:00Z',ignored:false}]};`,context);
const value=()=>vm.runInContext('AVGOOGLE.events[0]',context);
const save=end=>{vm.runInContext('AVGOOGLE_EDIT={key:AVGOOGLE.key,event:{...AVGOOGLE.events[0]}}',context);return context.avGoogleSave({end,ignored:false});};
const first=save('2030-01-01T13:00:00Z');
assert.equal(value().blocking_end,'2030-01-01T13:00:00Z','updates before server reply');
const second=save('2030-01-01T14:00:00Z');
const third=save('2030-01-01T15:00:00Z');
assert.equal(requests.length,1,'serializes same event');
requests[0].resolve({ok:true,json:async()=>({event:{...value(),blocking_end:requests[0].body.end}})});
await new Promise(resolve=>setImmediate(resolve));
assert.equal(value().blocking_end,'2030-01-01T15:00:00Z','old reply cannot overwrite latest input');
assert.equal(requests.length,2);
assert.equal(requests[1].body.end,'2030-01-01T15:00:00Z','coalesces intermediate edits');
requests[1].resolve({ok:false,json:async()=>({error:'offline'})});
await Promise.all([first,second,third]);
assert.equal(value().blocking_end,'2030-01-01T13:00:00Z','failure restores last confirmed save');
assert.match(messages[0],/offline/);
const fourth=save('2030-01-01T16:00:00Z');
vm.runInContext("AVGOOGLE={key:'other-week',events:[]}",context);
requests[2].resolve({ok:true,json:async()=>({event:{id:'one'}})});
await fourth;
assert.equal(vm.runInContext('AVGOOGLE.events.length',context),0,'navigation is not overwritten');
assert.equal(vm.runInContext('AVGOOGLE_SAVES.size',context),0);
vm.runInContext(`AVGOOGLE={key:'staff|week',events:[{id:'two',calendar_id:'primary',start:'2030-01-01T10:00:00Z',end:'2030-01-01T12:00:00Z',blocking_start:'2030-01-01T10:00:00Z',blocking_end:'2030-01-01T12:00:00Z',ignored:false}]};`,context);
const spanning=save('2030-01-01T13:00:00Z');
vm.runInContext("AVGOOGLE.key='staff|next-week'",context);
const nextWeek=save('2030-01-01T14:00:00Z');
assert.equal(requests.length,4,'same event across weeks shares queue');
requests[3].resolve({ok:true,json:async()=>({event:{...value(),blocking_end:requests[3].body.end}})});
await new Promise(resolve=>setImmediate(resolve));
assert.equal(requests.length,5);
let finishLoad;
context.api=()=>new Promise(resolve=>{finishLoad=resolve;});
const oldEvent={...value()};
const loading=context.avGoogleLoad({key:'staff|next-week',from:'2030-01-01T00:00:00Z',to:'2030-01-08T00:00:00Z'});
requests[4].resolve({ok:true,json:async()=>({event:{...value(),blocking_end:'2030-01-01T14:00:00Z'}})});
await Promise.all([spanning,nextWeek]);
finishLoad({ok:true,json:async()=>({connected:true,events:[{...oldEvent,blocking_end:'2030-01-01T12:00:00Z'}]})});
await loading;
assert.equal(value().blocking_end,'2030-01-01T14:00:00Z','late GET cannot overwrite completed save');
const missingLoad=context.avGoogleLoad({key:'staff|next-week',from:'2030-01-01T00:00:00Z',to:'2030-01-08T00:00:00Z'});
context.api=(path,options)=>new Promise(resolve=>requests.push({body:JSON.parse(options.body),resolve}));
const movedSave=save('2030-01-01T16:00:00Z');
requests[5].resolve({ok:true,json:async()=>({event:{...value()}})});
await movedSave;
finishLoad({ok:true,json:async()=>({connected:true,events:[]})});
await missingLoad;
assert.equal(value().blocking_end,'2030-01-01T16:00:00Z','late empty GET includes edited event overlapping range');
let renders=0;
Object.assign(context,{currentTab:'avset',AVDRAG:{},setTimeout:()=>1,clearTimeout:()=>{},renderQuiet:()=>{renders++;}});
context.api=async()=>({ok:true,json:async()=>({connected:true,events:[]})});
await context.avGoogleLoad({key:'staff|next-week'});
assert.equal(renders,0,'GET render is deferred during manual drag');
context.AVDRAG=null;context.avGoogleRefresh();
assert.equal(renders,1,'GET render resumes after drag');
console.log('availability optimistic/serial/coalescing/failure/navigation/cross-week/stale GET/drag: 16 checks passed');
