import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const P=require('../server/interview-preferences.js');
const at=h=>new Date('2030-11-02T'+h+':00+09:00').toISOString();
const group=(s,e)=>({slots:Array.from({length:(new Date(at(e))-new Date(at(s)))/1800000},(_,i)=>new Date(+new Date(at(s))+i*1800000).toISOString())});
const a=group('13:00','17:00'),b=group('15:00','19:00');
assert.equal(P.conflicts([a,b])[0].index,1);
assert.deepEqual(P.conflicts([a,b])[0].remaining,[{start:at('17:00'),end:at('19:00')}]);
assert.equal(P.conflicts([a,a])[0].duplicate,true);
assert.equal(P.conflicts([a,group('17:00','18:00')]).length,0);
assert.equal(P.conflicts([group('15:00','16:00'),a])[0].remaining.length,2);
assert.equal(P.conflicts([a,group('14:00','15:00')])[0].remaining.length,0);
assert.equal(P.fits(a,at('16:00'),60),true);
assert.equal(P.fits(a,at('16:30'),60),false);
assert.equal(P.fits({slots:[at('13:00'),at('14:00')]},at('13:00'),60),false);
assert.equal(P.fits({slots:[at('13:00'),at('13:30')],mode:'point'},at('13:00'),60),false);
assert.deepEqual(P.normalize([b,a]).map(g=>g.slots[0]),[at('15:00'),at('13:00')]);
assert.throws(()=>P.normalize([{slots:['invalid']}]),/候補/);
assert.deepEqual(P.groups({choices:[at('18:00'),at('13:00'),at('13:30')],choice_mode:'slot'}).map(g=>g.slots[0]),[at('18:00'),at('13:00')]);
assert.equal(P.groups({choices:[at('13:00'),at('18:00')],all_day:['2030-11-02'],choice_mode:'slot'}).length,1);
assert.equal(P.fits(P.groups({choices:[at('13:00'),at('18:00')],all_day:['2030-11-02'],choice_mode:'slot'})[0],at('13:00'),60),false);
assert.equal(P.groups({choices:[at('13:00'),at('13:30')]}).at(0).mode,'point');
assert.equal(P.groups({preference_groups:[group('13:00','14:00'),group('14:00','15:00')]}).length,2);
console.log('面談希望: 17件成功');
