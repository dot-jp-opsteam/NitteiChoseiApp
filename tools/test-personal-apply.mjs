export async function runPersonalApplyTests({api,tokens,check}){
  console.log('\n─────── 個人用の面談申請リンク ───────');
  const own=await api(tokens.staff,'GET','/api/staff/intern-invite-url');
  const other=await api(tokens.staff3,'GET','/api/staff/intern-invite-url');
  check('同じ支部でもスタッフごとにURLが異なる',own.json.url!==other.json.url,true);
  const token=String(own.json.url||'').split('/i/')[1];
  const page=await api(null,'GET','/api/apply/'+token);
  check('申請ページはURLの所有者1人だけを返す',(page.json.staff||[]).map(staff=>staff.id),['u_e2e_staff']);
  check('個人用URLの担当固定を明示',page.json.fixed_staff,true);
  check('担当者を指定しなくても本人の空き枠を取得',(await api(null,'GET',`/api/apply/${token}/slots?week=1`)).status,200);
  check('同支部の他人の空き枠に差し替えられない',(await api(null,'GET',`/api/apply/${token}/slots?staff_id=u_e2e_staff3`)).status,400);
  const grid=await api(null,'GET',`/api/apply/${token}/slots?week=1`);
  const open=(grid.json.grid||[]).flat().find(cell=>cell.state==='ok');
  if(!open)throw Error('個人用リンクの申請検査に必要な空き枠がありません');
  check('送信時も同支部の他人へ担当を変えられない',(await api(null,'POST',`/api/apply/${token}`,{name:'担当差替え検査',staff_id:'u_e2e_staff3',choices:[open.iso]})).status,400);
  const sent=await api(null,'POST',`/api/apply/${token}`,{name:'担当固定の申請検査',choices:[open.iso],choice_mode:'slot'});
  check('担当者IDを送らなくても申請できる',sent.status,200);
  const database=await api(tokens.staff,'GET','/api/db');
  check('面談はURLの所有者に届く',(database.json.interviews||[]).find(item=>item.intern_name==='担当固定の申請検査')?.staff_id,'u_e2e_staff');
  const otherToken=String(other.json.url||'').split('/i/')[1];
  const regen=await api(tokens.staff,'POST','/api/staff/intern-invite-url/regenerate');
  check('本人は自分のリンクを再発行できる',regen.status,200);
  check('再発行は別スタッフのURLを無効化しない',(await api(null,'GET','/api/apply/'+otherToken)).status,200);
  check('旧個人URLからの空き枠取得は拒否',(await api(null,'GET',`/api/apply/${token}/slots`)).status,404);
  const simultaneous=await Promise.all(Array.from({length:12},()=>api(tokens.staff4,'GET','/api/staff/intern-invite-url')));
  check('同時発行でも全て成功',simultaneous.every(result=>result.status===200),true);
  check('同時発行で本人のURLは1本だけ',new Set(simultaneous.map(result=>result.json.url)).size,1);
  const legacy=await api(null,'GET','/api/apply/legacy_e2e_branch_link');
  check('配布済みの支部共通URLは引き続き有効',legacy.status,200);
  check('旧URLのみ担当者選択を維持',legacy.json.fixed_staff,false);
  check('旧URLは同支部スタッフを選べる',(legacy.json.staff||[]).some(staff=>staff.id==='u_e2e_staff3'),true);
  const legacySlots=await api(null,'GET','/api/apply/legacy_e2e_branch_link/slots?staff_id=u_e2e_staff3&week=1');
  check('旧URLからの空き枠取得を維持',legacySlots.status,200);
  const legacyOpen=(legacySlots.json.grid||[]).flat().find(cell=>cell.state==='ok');
  if(!legacyOpen)throw Error('旧URLの検査に必要な空き枠がありません');
  check('旧URLからの申請を維持',(await api(null,'POST','/api/apply/legacy_e2e_branch_link',{name:'旧URLの互換性検査',staff_id:'u_e2e_staff3',choices:[legacyOpen.iso]})).status,200);
  const adminLink=await api(tokens.admin,'GET','/api/staff/intern-invite-url');
  const adminToken=String(adminLink.json.url||'').split('/i/')[1];
  const adminSlots=await api(null,'GET',`/api/apply/${adminToken}/slots?week=1`);
  const adminOpen=(adminSlots.json.grid||[]).flat().find(cell=>cell.state==='ok');
  if(!adminOpen)throw Error('支部なし管理者の空き枠がありません');
  check('支部なし管理者にも個人申請できる',(await api(null,'POST',`/api/apply/${adminToken}`,{name:'個人通知の非公開検査',choices:[adminOpen.iso]})).status,200);
  const adminDb=await api(tokens.admin,'GET','/api/db');
  check('支部なし所有者本人に申請通知が届く',adminDb.json.notifications.some(item=>item.msg.includes('個人通知の非公開検査')),true);
  for(const [label,actor] of [['同支部',tokens.staff],['他支部',tokens.staff2]]){
    const unrelated=await api(actor,'GET','/api/db');
    check(label+'の無関係なスタッフに個人通知を渡さない',unrelated.json.notifications.some(item=>item.msg.includes('個人通知の非公開検査')),false);
  }
  const ownAdmin=await api(tokens.admin,'GET','/api/staff/intern-invite-url?branch_id=b1');
  check('管理者が支部を指定してもURLの所有者は本人',ownAdmin.json.staff_id,'u_e2e_admin');
  const transferred=await api(tokens.admin,'PATCH','/api/admin/users/u_e2e_staff3',{nickname:'E2E-staff',role:'staff',branch_id:'b2'});
  check('検査用スタッフの支部異動が成功',transferred.status,200);
  const movedPage=await api(null,'GET','/api/apply/'+otherToken);
  check('異動後もURLの担当者は同じ本人',movedPage.json.staff?.[0]?.id,'u_e2e_staff3');
  check('異動後の所属表示を最新にする',movedPage.json.branch?.name,'大阪');
  await api(tokens.admin,'PATCH','/api/admin/users/u_e2e_staff3',{nickname:'E2E-staff',role:'intern',branch_id:'b2'});
  check('担当者がスタッフでなくなったURLは無効',(await api(null,'GET','/api/apply/'+otherToken)).status,404);
  check('役割変更後は空き枠も公開しない',(await api(null,'GET',`/api/apply/${otherToken}/slots`)).status,404);
  await api(tokens.admin,'PATCH','/api/admin/users/u_e2e_staff3',{nickname:'E2E-staff',role:'staff',branch_id:'b1'});
}
